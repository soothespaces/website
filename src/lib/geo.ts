export type LatLng = { lat: number; lng: number };

const EARTH_RADIUS_METERS = 6_371_000;

/**
 * Distance in meters between two map points. Shared by printer "nearby"
 * checks and, later, restroom points.
 */
/**
 * Whether a map point sits inside a GeoJSON ring. Coordinates are [lng, lat].
 * A repeated closing point is fine. Fewer than three corners is never inside.
 */
export function pointInPolygon(point: LatLng, ring: readonly (readonly [number, number])[]): boolean {
  if (ring.length < 3) return false;
  const x = point.lng;
  const y = point.lat;
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    const crosses = yi > y !== yj > y;
    if (!crosses || yj === yi) continue;
    const xAtY = ((xj - xi) * (y - yi)) / (yj - yi) + xi;
    if (x < xAtY) inside = !inside;
  }
  return inside;
}

export function distanceMeters(a: LatLng, b: LatLng): number {
  const toRad = (degrees: number) => (degrees * Math.PI) / 180;
  const lat1 = toRad(a.lat);
  const lat2 = toRad(b.lat);
  const dLat = lat2 - lat1;
  const dLng = toRad(b.lng - a.lng);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLng / 2) ** 2;
  return 2 * EARTH_RADIUS_METERS * Math.asin(Math.min(1, Math.sqrt(h)));
}
